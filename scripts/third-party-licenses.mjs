// Generates THIRD_PARTY_LICENSES.md with the licenses of the dependencies shipped in the app.
// Usage: pnpm licenses:generate
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// On Windows pnpm is a .cmd and needs a shell; cargo does not (and the "|" in the format would break cmd).
const run = (cmd, args, shell = false) =>
  execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell });

// Production JavaScript dependencies.
const npmByLicense = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"], process.platform === "win32"));
const npm = Object.values(npmByLicense)
  .flat()
  .flatMap((pkg) => pkg.versions.map((version) => ({ name: pkg.name, version, license: pkg.license })));

// Rust crates compiled into the Windows executable.
const tree = run("cargo", [
  "tree",
  "--manifest-path",
  "src-tauri/Cargo.toml",
  "-e",
  "normal",
  "--prefix",
  "none",
  "--target",
  "x86_64-pc-windows-msvc",
  "--format",
  "{p}|{l}",
]);
const crates = new Map();
for (const line of tree.split(/\r?\n/)) {
  const match = /^(\S+) v(\S+)(?: \([^)]*\))?(?: \(\*\))?\|(.*)$/.exec(line.trim());
  if (!match || match[1] === "nexus-terminal") continue;
  crates.set(`${match[1]}@${match[2]}`, { name: match[1], version: match[2], license: match[3] || "?" });
}

const table = (rows) =>
  ["| Package | Version | License |", "|---|---|---|"]
    .concat(
      rows
        .sort((a, b) => a.name.localeCompare(b.name))
        .map((r) => `| ${r.name} | ${r.version} | ${r.license.replace(/\|/g, "/")} |`),
    )
    .join("\n");

const summary = (rows) => {
  const counts = {};
  for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([license, n]) => `- ${license}: ${n}`)
    .join("\n");
};

const md = `# Third-party licenses

Generated by \`scripts/third-party-licenses.mjs\` (\`pnpm licenses:generate\`). Do not edit by hand.
Theme color palettes: see \`THIRD_PARTY_NOTICES.md\`.

## JavaScript dependencies (${npm.length})

${summary(npm)}

${table(npm)}

## Rust crates (${crates.size})

${summary([...crates.values()])}

${table([...crates.values()])}
`;

writeFileSync("THIRD_PARTY_LICENSES.md", md);
console.log(`THIRD_PARTY_LICENSES.md: ${npm.length} npm packages, ${crates.size} crates`);
